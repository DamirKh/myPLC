local nav = require("modules.ui_nav")

return function(t)
   t.test("header hides subpages from primary navigation", function()
      local html = nav.header({ title = "Обзор", subtitle = "Подзаголовок", active = "overview" })
      t.assert_true(html:find('href="/"', 1, true) ~= nil)
      t.assert_true(html:find('href="/history.lsp"', 1, true) ~= nil)
      t.assert_true(html:find('href="/admin/settings.lsp"', 1, true) ~= nil)
      t.assert_true(html:find("Датчики", 1, true) == nil)
      t.assert_true(html:find("Wi-Fi", 1, true) == nil)
      t.assert_true(html:find('class="active"', 1, true) ~= nil)
   end)

   t.test("header escapes title and subtitle", function()
      local html = nav.header({ title = "<Тёплый>", subtitle = "A&B", active = "history" })
      t.assert_true(html:find("&lt;Тёплый&gt;", 1, true) ~= nil)
      t.assert_true(html:find("A&amp;B", 1, true) ~= nil)
   end)

   t.test("theme button can be disabled", function()
      local on = nav.header({ title = "x", active = "overview" })
      local off = nav.header({ title = "x", active = "overview", theme = false })
      t.assert_true(on:find('id="themeToggle"', 1, true) ~= nil)
      t.assert_true(off:find('id="themeToggle"', 1, true) == nil)
   end)

   t.test("settings tabs include service, wifi and pin", function()
      local html = nav.settings_tabs("service")
      t.assert_true(html:find("Основные", 1, true) ~= nil)
      t.assert_true(html:find("Сервис", 1, true) ~= nil)
      t.assert_true(html:find("Wi-Fi", 1, true) ~= nil)
      t.assert_true(html:find("PIN", 1, true) ~= nil)
      t.assert_true(html:find("Заблокировать", 1, true) ~= nil)
      t.assert_true(html:find('href="/admin/sensors.lsp" class="active"', 1, true) ~= nil)
   end)
end
