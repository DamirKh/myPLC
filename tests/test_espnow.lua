local espnow = require("modules.espnow_provision")

local function bytes(...)
   return string.char(...)
end

return function(t)
   t.test("ESP-NOW MAC helpers", function()
      local mac = bytes(0x3c, 0x84, 0x27, 0xca, 0x27, 0x54)
      t.assert_eq(espnow.hex(mac), "3c8427ca2754")
      t.assert_eq(espnow.mac_text("3c8427ca2754"), "3c:84:27:ca:27:54")
      t.assert_eq(espnow.normalize_mac("3C:84:27:CA:27:54"), "3c8427ca2754")
      t.assert_true(espnow.valid_mac_hex("3c8427ca2754"))
      t.assert_false(espnow.valid_mac_hex("3c8427ca275"))
      t.assert_false(espnow.valid_mac_hex("zz8427ca2754"))
   end)

   t.test("ESP-NOW PROV packet format", function()
      local mac = bytes(1, 2, 3, 4, 5, 6)
      local token = bytes(0x11, 0x22, 0x33, 0x44)
      local packet, err = espnow.build_prov(mac, token, 6)
      t.assert_true(packet, err)
      t.assert_eq(#packet, 16)
      t.assert_eq(packet:sub(1, 4), "PROV")
      t.assert_eq(packet:byte(5), 1)
      t.assert_eq(packet:sub(6, 11), mac)
      t.assert_eq(packet:sub(12, 15), token)
      t.assert_eq(packet:byte(16), 6)
   end)

   t.test("ESP-NOW PROV rejects bad input", function()
      local ok = espnow.build_prov("short", bytes(1, 2, 3, 4), 6)
      t.assert_false(ok)
      ok = espnow.build_prov(bytes(1, 2, 3, 4, 5, 6), "123", 6)
      t.assert_false(ok)
      ok = espnow.build_prov(bytes(1, 2, 3, 4, 5, 6), bytes(1, 2, 3, 4), 0)
      t.assert_false(ok)
   end)

   t.test("ESP-NOW POK parsing and token check", function()
      local src = bytes(0x3c, 0x84, 0x27, 0xca, 0x27, 0x54)
      local token = bytes(1, 2, 3, 4)
      local packet = "POK" .. bytes(1) .. src .. token
      local parsed, err = espnow.parse_pok(packet, src, token)
      t.assert_true(parsed, err)
      t.assert_eq(parsed.mac, "3c8427ca2754")
      local bad = espnow.parse_pok(packet, src, bytes(1, 2, 3, 5))
      t.assert_false(bad)
      local other_src = bytes(1, 1, 1, 1, 1, 1)
      t.assert_false(espnow.parse_pok(packet, other_src, token))
   end)

   t.test("ESP-NOW XNW1 parsing", function()
      local src = bytes(1, 2, 3, 4, 5, 6)
      local packet = "XNW1" .. bytes(4, 3, 2, 1, 0x44, 0x33, 0x22, 0x11)
         .. string.rep("\0", 20)
      local parsed, err = espnow.parse_xnw1(packet, src)
      t.assert_true(parsed, err)
      t.assert_eq(parsed.seq, 0x01020304)
      t.assert_eq(parsed.uptime_ms, 0x11223344)
      t.assert_eq(parsed.mac, "010203040506")
   end)

   t.test("ESP-NOW runtime records node statistics", function()
      local runtime = espnow.new_runtime()
      local src = bytes(1, 2, 3, 4, 5, 6)
      local token = bytes(9, 8, 7, 6)
      local pok = "POK" .. bytes(1) .. src .. token
      local kind, parsed = espnow.note_packet(runtime, pok, src, {rssi = -50, channel = 6}, 1000, token)
      t.assert_eq(kind, "pok")
      t.assert_eq(parsed.mac, "010203040506")
      local node = runtime.nodes["010203040506"]
      t.assert_true(node)
      t.assert_eq(node.last_seen, 1000)
      t.assert_eq(node.last_rssi, -50)
      t.assert_eq(node.channel, 6)
      t.assert_eq(node.packets, 1)
      t.assert_true(node.pok)
      t.assert_eq(node.last_magic, "POK")
   end)

   t.test("ESP-NOW node list merges config and runtime", function()
      local runtime = espnow.new_runtime()
      local src = bytes(1, 2, 3, 4, 5, 6)
      espnow.note_packet(runtime, "XNW1" .. string.rep("\0", 8), src, {rssi = -42, channel = 3}, 2000, nil)
      local list = espnow.nodes(runtime, {
         ["010203040506"] = { mac = "010203040506", label = "room" },
         ["aabbccddeeff"] = { mac = "aabbccddeeff", label = "spare" },
      })
      t.assert_eq(#list, 2)
      t.assert_eq(list[1].mac, "010203040506")
      t.assert_eq(list[1].label, "room")
      t.assert_eq(list[1].last_rssi, -42)
      t.assert_true(list[1].known)
      t.assert_eq(list[2].mac, "aabbccddeeff")
      t.assert_false(list[2].last_seen)
   end)

   t.test("ESP-NOW config node helpers", function()
      local cfg = { espnow = { nodes = {} } }
      local node, err = espnow.add_node(cfg, "3C:84:27:CA:27:54", "sensor")
      t.assert_true(node, err)
      t.assert_eq(node.mac, "3c8427ca2754")
      t.assert_eq(cfg.espnow.nodes["3c8427ca2754"].label, "sensor")
      t.assert_true(espnow.remove_node(cfg, "3c8427ca2754"))
      t.assert_false(cfg.espnow.nodes["3c8427ca2754"])
   end)
end
